// Destructive operations are confined to these in-memory fixtures, never AWS.
import assert from 'node:assert/strict'
import { withFixtureBrowser } from './browser-fixture.mjs'

let checks = 0
function pass(label) { checks++; console.log('PASS: ' + label) }
await withFixtureBrowser(async ({ evaluate, waitFor, go, login, requests, command }) => {
  const deletes = () => requests.filter(request => request.method === 'DELETE')
  async function button(label, dialog = false) {
    await evaluate(`Array.from(document.querySelectorAll(${JSON.stringify(dialog ? 'dialog[open] button' : 'main button')})).find(button => button.textContent.trim() === ${JSON.stringify(label)}).click()`)
  }
  async function confirm() {
    await waitFor(`Boolean(document.querySelector('dialog[open]'))`, 'delete confirmation')
    await button('Eliminar definitivamente', true)
  }
  async function logout() {
    await evaluate(`localStorage.clear(); location.replace('/login')`)
    await waitFor(`Boolean(document.querySelector('input[type="email"]'))`, 'logout')
  }
  const hasButton = label => `Array.from(document.querySelectorAll('main button')).some(button => button.textContent.trim() === ${JSON.stringify(label)})`
  await login('student@example.test')
  await evaluate(`(async () => { const service = await import('/src/services/EvaluationService.ts'); await service.evaluationSubmit('EVL-TEST-001', { answers: [0, 0, 0] }); })()`)
  await go('/app/courses/CRS-TEST-001/materials')
  await waitFor(`document.body.textContent.includes('Guía de arquitectura')`, 'student materials')
  assert.equal(await evaluate(hasButton('Eliminar material')), false)
  assert.equal(await evaluate(hasButton('Eliminar curso')), false)
  await go('/app/evaluations/EVL-TEST-001')
  await waitFor(`Boolean(document.querySelector('.quiz-result'))`, 'student saved result')
  assert.equal(await evaluate(hasButton('Eliminar evaluación')), false)
  pass('student views never expose course, material or evaluation deletion')

  await logout()
  await login('teacher@example.test')
  await go('/app/courses/CRS-TEST-001/materials')
  await waitFor(hasButton('Eliminar material'), 'teacher owns upload')
  pass('teacher can delete their own upload')
  await command('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true })
  assert.equal(await evaluate(`document.documentElement.scrollWidth <= innerWidth`), true)
  assert.equal(await evaluate(`(() => { const element = Array.from(document.querySelectorAll('main button')).find(button => button.textContent.trim() === 'Eliminar material'); const rect = element.getBoundingClientRect(); return rect.left >= 0 && rect.right <= innerWidth; })()`), true)
  await command('Emulation.clearDeviceMetricsOverride')
  pass('download and material deletion controls fit the mobile layout')
  await go('/app/courses/CRS-A-DEADC0DE')
  await waitFor(`document.querySelector('h1')?.textContent === 'Curso de otro docente'`, 'other teacher course')
  assert.equal(await evaluate(hasButton('Eliminar curso')), false)
  await go('/app/evaluations/EVL-TEST-001')
  await waitFor(`Boolean(document.querySelector('.badge-published'))`, 'published evaluation')
  assert.equal(await evaluate(hasButton('Eliminar evaluación')), false)
  pass('teacher cannot delete another author course or their own published evaluation')
  const draftId = await evaluate(`(async () => (await (await import('/src/services/EvaluationService.ts')).evaluationCreate({ courseId: 'CRS-TEST-001', title: 'Borrador para eliminar', questions: [] })).evaluationId)()`)
  await go('/app/evaluations/' + draftId)
  await waitFor(hasButton('Eliminar evaluación'), 'owned draft')
  await button('Eliminar evaluación')
  await confirm()
  await waitFor(`location.pathname === '/app/courses/CRS-TEST-001/evaluations'`, 'draft deletion navigation')
  assert.equal(deletes().filter(request => request.url.endsWith('/evaluations/' + draftId)).length, 1)
  pass('teacher deletes an owned draft with one DELETE and returns to the course list')

  await logout()
  await login('admin@example.test')
  await go('/app/users/USR-TEST-ADMIN')
  await waitFor(`document.querySelector('h1')?.textContent === 'admin'`, 'own administrator detail')
  assert.equal(await evaluate(hasButton('Eliminar usuario')), false)
  pass('administrator cannot delete their own account from the interface')
  await go('/app/users/USR-TEST-STUDENT-003')
  await waitFor(hasButton('Eliminar usuario'), 'other user detail')
  const initialDeleteCount = deletes().length
  await button('Eliminar usuario')
  await waitFor(`Boolean(document.querySelector('dialog[open]'))`, 'confirmation before deleting user')
  assert.equal(deletes().length, initialDeleteCount)
  await button('Cancelar', true)
  await waitFor(`!document.querySelector('dialog[open]')`, 'cancel confirmation')
  assert.equal(deletes().length, initialDeleteCount)
  pass('opening and cancelling confirmation never sends DELETE')
  await button('Eliminar usuario')
  await confirm()
  await waitFor(`Boolean(document.querySelector('dialog[open] .error-state'))`, 'business failure is visible')
  assert.equal(await evaluate(`location.pathname`), '/app/users/USR-TEST-STUDENT-003')
  assert.equal(deletes().length, initialDeleteCount + 1)
  pass('HTTP 200 FORBIDDEN keeps the record and dialog without an automatic retry')
  await button('Cancelar', true)
  await button('Eliminar usuario')
  await waitFor(`Boolean(document.querySelector('dialog[open]'))`, 'reopened delete dialog')
  await evaluate(`(() => { const button = Array.from(document.querySelectorAll('dialog[open] button')).find(button => button.textContent.trim() === 'Eliminar definitivamente'); button.click(); button.click(); })()`)
  await waitFor(`location.pathname === '/app/users' && Boolean(document.querySelector('tbody'))`, 'successful user deletion')
  assert.equal(deletes().length, initialDeleteCount + 2)
  assert.equal(await evaluate(`(async () => { try { await (await import('/src/services/AuthService.ts')).userFindId('USR-TEST-STUDENT-003'); return 'exists'; } catch (error) { return error.code; } })()`), 'NOT_FOUND')
  pass('confirmed user deletion navigates back, refreshes cache and blocks double clicks')

  await go('/app/enrollments?courseId=CRS-TEST-001')
  await waitFor(hasButton('Eliminar matrícula'), 'enrollment row')
  await button('Eliminar matrícula')
  await confirm()
  await waitFor(`document.body.textContent.includes('Sin matrículas en esta consulta')`, 'enrollment removed from list')
  const enrollmentDelete = deletes().find(request => new URL(request.url).pathname.endsWith('/enrollments'))
  assert.equal(new URL(enrollmentDelete.url).searchParams.get('courseId'), 'CRS-TEST-001')
  assert.equal(new URL(enrollmentDelete.url).searchParams.get('studentId'), 'USR-TEST-STUDENT')
  assert.equal(enrollmentDelete.postData, undefined)
  pass('enrollment deletion sends both query IDs and refreshes the current list')
  await go('/app/courses/CRS-TEST-001/materials')
  await waitFor(hasButton('Eliminar material'), 'material delete control')
  await button('Eliminar material')
  await confirm()
  await waitFor(`document.body.textContent.includes('Un estante por llenar')`, 'material removed from library')
  assert.ok(deletes().some(request => request.url.endsWith('/materials/CNT-TEST-001')))
  pass('material deletion removes its library row without deleting the course')
  await go('/app/evaluations/EVL-TEST-001')
  await waitFor(hasButton('Eliminar evaluación'), 'admin can delete published evaluation')
  await button('Eliminar evaluación')
  await waitFor(`document.querySelector('dialog[open]')?.textContent.includes('calificaciones existentes se conservan')`, 'evaluation non-cascade explanation')
  await confirm()
  await waitFor(`location.pathname === '/app/courses/CRS-TEST-001/evaluations' && !document.querySelector('.evaluation-row') && !document.querySelector('.skeleton-group')`, 'evaluation removed from list')
  await go('/app/evaluations/EVL-TEST-001/result?studentId=USR-TEST-STUDENT')
  await waitFor(`document.querySelector('.quiz-result')?.textContent.includes('100%')`, 'retained evaluation result')
  pass('admin deletes a published evaluation while its existing server result remains queryable')
  await go('/app/courses')
  await waitFor(`Boolean(document.querySelector('input[type="search"]')) && !document.querySelector('.skeleton-group')`, 'course search')
  await evaluate(`(() => { const input = document.querySelector('input[type="search"]'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(input, 'CRS-A-BCB2FDD0'); input.dispatchEvent(new Event('input', { bubbles: true })); })()`)
  await waitFor(`document.querySelector('.course-card h3')?.textContent === 'MATE23'`, 'cached exact course search')
  await go('/app/courses/CRS-A-BCB2FDD0')
  await waitFor(hasButton('Eliminar curso'), 'course deletion control')
  await button('Eliminar curso')
  await waitFor(`document.querySelector('dialog[open]')?.textContent.includes('matrículas, materiales y evaluaciones asociados se conservan')`, 'course non-cascade explanation')
  await confirm()
  await waitFor(`location.pathname === '/app/courses' && !document.querySelector('.skeleton-group')`, 'course deleted')
  await evaluate(`(() => { const input = document.querySelector('input[type="search"]'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(input, 'CRS-A-BCB2FDD0'); input.dispatchEvent(new Event('input', { bubbles: true })); })()`)
  await waitFor(`document.querySelector('.empty-state h3')?.textContent === 'Sin coincidencias' && !document.querySelector('.skeleton-group')`, 'deleted exact search no longer cached')
  assert.equal(await evaluate(`(async () => (await (await import('/src/services/EnrollmentService.ts')).enrollmentList({ courseId: 'CRS-A-BCB2FDD0' })).items.length)()`), 1)
  pass('course deletion clears exact/detail caches and retains related enrollment records')
}, { searchFixtures: true, deletionScenario: 'fail-first-user' })
console.log(`${checks} deletion browser checks passed against disposable local fixtures; no AWS deletions`)
